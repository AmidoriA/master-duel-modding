    /// <summary>
    /// Blocks interaction with a dim overlay. Avoids Window.IsEnabled=false, which
    /// forces ListBox/ListBoxItem into the default disabled (white) chrome.
    /// </summary>
    private void SetUiBusy(bool busy)
    {
        if (busy)
        {
            if (_uiBusyDepth++ == 0)
            {
                MainContent.IsHitTestVisible = false;
                BusyOverlay.Visibility = Visibility.Visible;
                Cursor = Cursors.Wait;
            }
            return;
        }

        if (_uiBusyDepth == 0)
            return;
        if (--_uiBusyDepth != 0)
            return;

        MainContent.IsHitTestVisible = true;
        BusyOverlay.Visibility = Visibility.Collapsed;
        ClearValue(CursorProperty);
    }
    private static DispatcherTimer CreateSearchDebounceTimer(EventHandler tick)
    {
        var timer = new DispatcherTimer { Interval = TimeSpan.FromMilliseconds(SearchDebounceMs) };
        timer.Tick += tick;
        return timer;
    }

    private void OnLoaded(object sender, RoutedEventArgs e)
    {
        try
        {
            _backupRoot = Path.Combine(AppContext.BaseDirectory, "backups");
            ToolsBackupPathBox.Text = _backupRoot;
            _modService = new CardArtModService(backupRoot: _backupRoot);
            _overFrameService = new OverFrameModService(backupRoot: _backupRoot);
            _autoOverFrameArtService = new AutoOverFrameArtService();

            OpenFixedDatabases();

            var discovered = GamePathLocator.FindSteamMasterDuelPaths();
            if (discovered.Count == 1)
            {
                SetGamePath(discovered[0]);
            }
            else if (_database?.GetStoredGamePath() is string stored &&
                     GamePathLocator.IsValidGamePath(stored, out _))
            {
                SetGamePath(stored);
            }

            Status($"Loaded. Cards in DB: {_database?.CountCards() ?? 0}. Discovered installs: {discovered.Count}.");
            ApplyResultsViewMode(_useThumbnailView);
            if (_database is not null)
            {
                RunSearch();
                RunOfSearch();
                RefreshOfGateStatusFromCache();
                RunDatabaseQuery(resetOffset: true);
            }

            UpdateHomePathsExpanderExpanded();
        }
        catch (Exception ex)
        {
            Status("Startup error: " + ex.Message);
            MessageBox.Show(ex.Message, AppCaption, MessageBoxButton.OK, MessageBoxImage.Error);
        }
    }

    /// <summary>
