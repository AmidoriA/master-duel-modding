    private static void ApplyDebouncedTextSearch(string? text, Action runSearch, Action clearPartialQuery)
    {
        var trimmed = text?.Trim() ?? "";
        if (trimmed.Length == 0)
        {
            runSearch();
            return;
        }

        if (trimmed.Length < AutoSearchMinLength)
        {
            clearPartialQuery();
            return;
        }

        runSearch();
    }

