    private async Task EnsureOfGateAsync(bool showErrors)
    {
        if (_overFrameService is null)
            return;
        if (string.IsNullOrWhiteSpace(GamePathBox.Text))
        {
            if (showErrors)
                MessageBox.Show("Set the Master Duel LocalData path first.", "Floowan");
            return;
        }

        SetUiBusy(true);
        OfGateStatusText.Text = "Scanning for of_card_asset…";
        Status("Scanning for of_card_asset…");
        var gamePath = GamePathBox.Text;
        var progress = new Progress<string>(msg =>
        {
            OfGateStatusText.Text = msg;
            Status(msg);
        });

        try
        {
            var result = await Task.Run(() =>
                _overFrameService.EnsureGateLocated(gamePath, _database, progress));
            if (result.Success)
            {
                _ofGateReady = true;
                OfGateStatusText.Text = result.Message + (result.BundleId is null ? "" : $" ({result.BundleId})");
                Status(result.Message);
                if (_database is not null)
                {
                    try
                    {
                        var marked = _overFrameService.SyncDatabaseFromGate(gamePath, _database, progress);
                        Status($"{result.Message} Synced {marked} over-frame flag(s).");
                        RunOfSearch();
                    }
                    catch (Exception syncEx)
                    {
                        Status(result.Message + " Sync skipped: " + syncEx.Message);
                    }
                }

                RefreshOfGateEntryStatus();
            }
            else
            {
                _ofGateReady = false;
                OfGateStatusText.Text = result.Message;
                Status(result.Message);
                if (showErrors)
                    MessageBox.Show(result.Message, "Floowan", MessageBoxButton.OK, MessageBoxImage.Warning);
            }
        }
        catch (Exception ex)
        {
            _ofGateReady = false;
            OfGateStatusText.Text = "Scan failed: " + ex.Message;
            Status(OfGateStatusText.Text);
            if (showErrors)
                MessageBox.Show(ex.Message, "Floowan", MessageBoxButton.OK, MessageBoxImage.Error);
        }
        finally
        {
            SetUiBusy(false);
        }
    }

    private void LoadOfCurrentPreview()
    {
        if (_ofSelected is null || _overFrameService is null || string.IsNullOrWhiteSpace(GamePathBox.Text))
            return;

        try
        {
            CleanupOfPreviewTemp();
            _ofPreviewTempPath = Path.Combine(Path.GetTempPath(), $"floowan-of-preview-{Guid.NewGuid():N}.png");
            // Always extract the live bundle texture as-is (full canvas). Do not art-hole-crop.
            _overFrameService.ExtractCardArt(GamePathBox.Text, _ofSelected, _ofPreviewTempPath);
            var info = _overFrameService.GetTextureInfo(GamePathBox.Text, _ofSelected);
            _ofLiveTextureIsOverframe = _ofSelected.IsOverframe
                || OverFrameAutoArtComposer.IsOverFrameTextureSize(info.Width, info.Height);

            // Already-OF textures use ??4 foil mask — flatten for on-screen visibility.
            // Normal 512?512 illusts load as-is.
            OfCurrentArtImage.Source = _ofLiveTextureIsOverframe
                ? LoadOfComposePreview(_ofPreviewTempPath)
                : LoadBitmap(_ofPreviewTempPath);
            ApplyOfPreviewLayout(hasReplacement: !string.IsNullOrWhiteSpace(_ofReplacementImagePath));

            OfDetailText.Text = _ofLiveTextureIsOverframe
                ? $"Live over-frame '{info.Name}' {info.Width}x{info.Height} format={info.Format}. Showing full {OverFrameConstants.Width}x{OverFrameConstants.Height} canvas (foil-mask flattened for preview)."
                : $"Texture '{info.Name}' {info.Width}x{info.Height} format={info.Format}. Normal art — Auto-create builds {OverFrameConstants.Width}x{OverFrameConstants.Height} RGBA32.";
        }
        catch (Exception ex)
        {
            OfCurrentArtImage.Source = null;
            _ofLiveTextureIsOverframe = false;
            OfDetailText.Text = "Preview failed: " + ex.Message;
        }
    }

    /// <summary>
    /// Normal cards: replacement replaces the pane. Already-OF cards: side-by-side
    /// live OF canvas + queued replacement so the full 704?1024 face stays visible.
    /// </summary>
    private void ApplyOfPreviewLayout(bool hasReplacement)
    {
        if (OfCurrentPreviewCol is null || OfReplacementPreviewCol is null)
            return;

        if (hasReplacement && _ofLiveTextureIsOverframe)
        {
            OfCurrentPreviewCol.Width = new GridLength(1, GridUnitType.Star);
            OfReplacementPreviewCol.Width = new GridLength(1, GridUnitType.Star);
            OfCurrentArtImage.Opacity = 1.0;
            OfReplacementImage.Opacity = 1.0;
        }
        else if (hasReplacement)
        {
            OfCurrentPreviewCol.Width = new GridLength(0);
            OfReplacementPreviewCol.Width = new GridLength(1, GridUnitType.Star);
            OfCurrentArtImage.Opacity = 0.0;
            OfReplacementImage.Opacity = 1.0;
        }
        else
        {
            OfCurrentPreviewCol.Width = new GridLength(1, GridUnitType.Star);
            OfReplacementPreviewCol.Width = new GridLength(0);
            OfCurrentArtImage.Opacity = 1.0;
            OfReplacementImage.Opacity = 0.0;
        }
    }

    private async void OfPreview_Click(object sender, RoutedEventArgs e)
