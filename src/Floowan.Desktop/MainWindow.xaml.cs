    private static string FormatCreatedAtDisplay(string? createdAt)
    {
        if (string.IsNullOrWhiteSpace(createdAt))
            return "";
        if (!DateTimeOffset.TryParse(createdAt, null, System.Globalization.DateTimeStyles.RoundtripKind, out var dto))
            return createdAt;
        return dto.ToLocalTime().ToString("yyyy-MM-dd HH:mm:ss") + " (local)";
    }

    /// <summary>
    /// Loads live bundle art for the Database tab. Over-frame (DB flag and/or 704ร—1024)
    /// uses foil-flattened full-canvas preview (same as Over-frame tab); normal illusts
    /// load as-is with Uniform stretch so aspect is preserved.
    /// </summary>
    private void LoadDatabaseArtPreview(CardRecord card)
    {
        if (_modService is null || string.IsNullOrWhiteSpace(GamePathBox.Text))
        {
            ClearDatabaseArtPreview();
            DbArtMetaText.Text = "Set the Master Duel LocalData path on Home to preview art.";
            return;
        }

        if (string.IsNullOrWhiteSpace(card.Bundle))
        {
            ClearDatabaseArtPreview();
            DbArtMetaText.Text = "No bundle on this card row.";
            return;
        }

        try
        {
            CleanupDbPreviewTemp();
            _dbPreviewTempPath = Path.Combine(Path.GetTempPath(), $"floowan-db-preview-{Guid.NewGuid():N}.png");
            _modService.ExtractCardArt(GamePathBox.Text, card, _dbPreviewTempPath);
            var info = _modService.GetTextureInfo(GamePathBox.Text, card);
            var isOverframe = CardArtModService.IsLiveOverFrameTexture(card.IsOverframe, info.Width, info.Height);

            DbArtPreviewImage.Source = isOverframe
                ? LoadOfComposePreview(_dbPreviewTempPath)
                : LoadBitmap(_dbPreviewTempPath);

            DbArtMetaText.Text = isOverframe
                ? $"Over-frame '{info.Name}' {info.Width}ร—{info.Height} ({info.Format})"
                : $"Texture '{info.Name}' {CardArtTextureSizes.Describe(info.Width, info.Height)} ({info.Format})";
        }
        catch (Exception ex)
        {
            ClearDatabaseArtPreview();
            DbArtMetaText.Text = "Preview failed: " + ex.Message;
        }
    }

    private void ClearDatabaseArtPreview()
    {
        DbArtPreviewImage.Source = null;
        CleanupDbPreviewTemp();
        DbArtMetaText.Text = "Select a card to preview live art.";
    }

    private void CleanupDbPreviewTemp()
    {
        if (_dbPreviewTempPath is not null && File.Exists(_dbPreviewTempPath))
        {
            try { File.Delete(_dbPreviewTempPath); } catch { /* ignore */ }
        }
        _dbPreviewTempPath = null;
    }

