    /// <summary>
    /// True when LocalData is a non-empty valid player folder (unity3d + 0000) and master DB is open.
    /// </summary>
    private bool IsHomeConfigured()
    {
        return _database is not null
            && GamePathLocator.IsValidGamePath(GamePathBox.Text, out _);
    }

    /// <summary>
    /// Opens master <c>database.db</c> and <c>user.db</c> beside the executable
    /// (<see cref="AppContext.BaseDirectory"/>). No browsable override.
    /// </summary>
    private void OpenFixedDatabases()
    {
        var path = MasterDatabasePaths.ResolveDefaultPath();
        if (!File.Exists(path))
        {
            Status("Missing database.db beside the app: " + path);
            return;
        }

        _database?.Dispose();
        _database = new CardDatabase(path, UserDatabasePaths.ResolveDefaultPath());
        ApplyDatabaseOptionalColumnsVisibility();

        RefreshOfGateStatusFromCache();
        UpdateHomePathsExpanderExpanded();
    }

    /// <summary>
    /// Shows card_type / created_at UI only when those master columns exist
    /// (populated by Tools DB update / #30). Absent columns stay hidden.
    /// </summary>
    private void ApplyDatabaseOptionalColumnsVisibility()
    {
        var showType = _database?.HasCardTypeColumn == true;
        var showCreated = _database?.HasCreatedAtColumn == true;

        if (DbColCardType is not null)
            DbColCardType.Visibility = showType ? Visibility.Visible : Visibility.Collapsed;
        if (DbColCreatedAt is not null)
            DbColCreatedAt.Visibility = showCreated ? Visibility.Visible : Visibility.Collapsed;

        var typeVis = showType ? Visibility.Visible : Visibility.Collapsed;
        var createdVis = showCreated ? Visibility.Visible : Visibility.Collapsed;
        if (DbEditCardTypeLabel is not null) DbEditCardTypeLabel.Visibility = typeVis;
        if (DbEditCardTypeBox is not null) DbEditCardTypeBox.Visibility = typeVis;
        if (DbEditCreatedAtLabel is not null) DbEditCreatedAtLabel.Visibility = createdVis;
        if (DbEditCreatedAtBox is not null) DbEditCreatedAtBox.Visibility = createdVis;
    }

