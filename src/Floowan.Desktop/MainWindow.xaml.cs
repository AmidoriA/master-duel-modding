    /// <summary>
    /// Resolve clean source art, run rembg + frame compose to a temp 704x1024 PNG,
    /// and queue it as the OF replacement preview. Does not apply to the game.
    /// </summary>
    /// <param name="frameStyleOverride">
    /// When set (e.g. Preview defaulting to Effect), use this instead of the Frame dropdown.
    /// Auto-create callers omit this so an empty dropdown still fails with "Frame style is required."
    /// </param>
    private async Task<string> ComposeAutoOverFrameReplacementAsync(
        CardRecord card,
        IProgress<string>? progress,
        CardFrameStyle? frameStyleOverride = null)
    {
        if (_overFrameService is null || _autoOverFrameArtService is null)
            throw new InvalidOperationException("Over-frame services are not initialized.");
        if (string.IsNullOrWhiteSpace(GamePathBox.Text))
            throw new InvalidOperationException("Master Duel LocalData path is not set.");

        string? autoSourcePath = null;
        try
        {
            autoSourcePath = Path.Combine(
                Path.GetTempPath(),
                $"floowan-of-source-{Guid.NewGuid():N}.png");
            var sourceLabel = _overFrameService.ResolveAutoCreateSourceArt(
                GamePathBox.Text, card, autoSourcePath);
            progress?.Report($"Auto-create source: {sourceLabel}");

            CleanupOfAutoGeneratedTemp();
            _ofAutoGeneratedTempPath = Path.Combine(
                Path.GetTempPath(),
                $"floowan-of-auto-{Guid.NewGuid():N}.png");
            var frameStyle = frameStyleOverride
                ?? GetSelectedOfComposeFrameStyle()
                ?? throw new InvalidOperationException("Frame style is required.");
            // Callers may pass a solid override (e.g. tests); OF always uses gradient chrome.
            frameStyle = CardFrameTemplates.ToOfGradientStyle(frameStyle);
            var linkMarkers = await TryResolveLinkMarkersAsync(card, frameStyle, progress);
            await _autoOverFrameArtService.CreateAsync(
                autoSourcePath,
                _ofAutoGeneratedTempPath,
                frameStyle,
                progress,
                linkMarkers: linkMarkers);

            _ofReplacementImagePath = _ofAutoGeneratedTempPath;
            Status($"Auto-generated 704x1024 replacement ready ({CardTypeLabels.ToLabel(CardFrameTemplates.GetSolidBaseStyle(frameStyle))}). Review before Apply.");
            OfReplacementImage.Source = LoadOfComposePreview(_ofAutoGeneratedTempPath);
            ApplyOfPreviewLayout(hasReplacement: true);
            return sourceLabel;
        }
        finally
        {
            if (autoSourcePath is not null && File.Exists(autoSourcePath))
            {
                try { File.Delete(autoSourcePath); } catch { /* ignore */ }
            }
        }
    }

    /// <summary>
    /// Soft timeout for optional live CARD_Prop marker loads (DB miss only).
    /// </summary>
    private static readonly TimeSpan LinkMarkerLoadTimeout = TimeSpan.FromSeconds(30);

    /// <summary>
    /// Resolves Link arrow markers for OF compose: prefer catalog <see cref="CardRecord.LinkMarkers"/>,
    /// optionally fall back to a timed live CARD_Prop load when the DB value is missing.
    /// </summary>
    private async Task<LinkMarkerMask?> TryResolveLinkMarkersAsync(
        CardRecord card,
        CardFrameStyle frameStyle,
        IProgress<string>? progress = null)
    {
        if (!LinkArrowOverlay.NeedsArrowOverlay(frameStyle))
            return null;

        // Prefer shipped/updated catalog — avoid LocalData scans on Preview.
        var fromDb = card.LinkMarkers ?? _database?.GetById(card.Id)?.LinkMarkers;
        if (fromDb is { } dbMarkers)
        {
            progress?.Report(
                $"Link markers for '{card.DisplayName}': 0x{(byte)dbMarkers:X2} " +
                $"({LinkMarkerMaskConvert.Count(dbMarkers)} arrows, from catalog)");
            return dbMarkers;
        }

        if (string.IsNullOrWhiteSpace(GamePathBox.Text))
        {
            progress?.Report(
                $"No catalog link markers for id {card.Id}; Link arrows will not be redrawn.");
            return null;
        }

        var gamePath = GamePathBox.Text;
        var cardId = card.Id;
        var displayName = card.DisplayName;
        try
        {
            progress?.Report("Catalog missing link markers; trying live CARD_Prop…");
            using var cts = new CancellationTokenSource(LinkMarkerLoadTimeout);
            // WaitAsync guarantees we return even if AssetsTools blocks inside LoadBundleFile
            // (token alone cannot abort a native/uncooperative hang).
            var loadTask = Task.Run(
                () =>
                {
                    if (_linkMarkerLoader.TryGetMarkers(
                            gamePath, cardId, out var found, cts.Token))
                        return (LinkMarkerMask?)found;
                    return null;
                },
                CancellationToken.None);
            var markers = await loadTask.WaitAsync(cts.Token).ConfigureAwait(true);

            if (markers is not null)
            {
                progress?.Report(
                    $"Link markers for '{displayName}': 0x{(byte)markers.Value:X2} " +
                    $"({LinkMarkerMaskConvert.Count(markers.Value)} arrows, live)");
                return markers;
            }

            progress?.Report(
                $"No CARD_Prop link markers for id {cardId}; Link arrows will not be redrawn.");
            return null;
        }
        catch (OperationCanceledException)
        {
            progress?.Report(
                "Timed out loading CARD_Prop link markers; Link arrows will not be redrawn.");
            return null;
        }
        catch (Exception ex)
        {
            progress?.Report("Could not load CARD_Prop link markers: " + ex.Message);
            return null;
        }
    }

