    /// <summary>
    /// Resolve clean source art, run rembg + frame compose to a temp 704x1024 PNG,
    /// and queue it as the OF replacement preview. Does not apply to the game.
    /// </summary>
    private async Task<string> ComposeAutoOverFrameReplacementAsync(
        CardRecord card,
        IProgress<string>? progress)
    {
        if (_overFrameService is null || _autoOverFrameArtService is null)
            throw new InvalidOperationException("Over-frame services are not initialized.");
        if (string.IsNullOrWhiteSpace(GamePathBox.Text))
            throw new InvalidOperationException("Master Duel LocalData path is not set.");

        string? autoSourcePath = null;
        try
        {
            autoSourcePath = Path.Combine(
                Path.GetTempPath(),
                $"floowan-of-source-{Guid.NewGuid():N}.png");
            var sourceLabel = _overFrameService.ResolveAutoCreateSourceArt(
                GamePathBox.Text, card, autoSourcePath);
            progress?.Report($"Auto-create source: {sourceLabel}");

            CleanupOfAutoGeneratedTemp();
            _ofAutoGeneratedTempPath = Path.Combine(
                Path.GetTempPath(),
                $"floowan-of-auto-{Guid.NewGuid():N}.png");
            var frameStyle = GetSelectedOfFrameStyle()
                ?? throw new InvalidOperationException("Frame style is required.");
            await _autoOverFrameArtService.CreateAsync(
                autoSourcePath,
                _ofAutoGeneratedTempPath,
                frameStyle,
                progress);

            _ofReplacementImagePath = _ofAutoGeneratedTempPath;
            OfImagePathText.Text =
                "Auto-generated 704x1024 replacement (review before Apply): " +
                _ofAutoGeneratedTempPath;
            OfReplacementImage.Source = LoadOfComposePreview(_ofAutoGeneratedTempPath);
            ApplyOfPreviewLayout(hasReplacement: true);
            return sourceLabel;
        }
        finally
        {
            if (autoSourcePath is not null && File.Exists(autoSourcePath))
            {
                try { File.Delete(autoSourcePath); } catch { /* ignore */ }
            }
        }
    }

