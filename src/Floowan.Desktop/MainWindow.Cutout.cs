using System.Windows;
using System.Windows.Controls;
using Floowan.Core.Imaging;
using Floowan.Desktop.Localization;

namespace Floowan.Desktop;

/// <summary>
/// Over-frame "Subject cutout" picker: isnet-anime or SAM 3 + ViTMatte, plus the SAM 3
/// held-items toggle. Stored in user.db and pushed into the shared
/// <see cref="AutoOverFrameArtService"/>, so Custom OF "Auto detect" follows it too.
/// </summary>
public partial class MainWindow
{
    private bool _cutoutSettingsLoading;

    private void LoadCutoutSettings()
    {
        _cutoutSettingsLoading = true;
        try
        {
            var model = SubjectCutoutModels.FromId(_database?.GetStoredCutoutModel());
            OfCutoutModelBox.SelectedItem = model == SubjectCutoutModel.Sam3 ? OfCutoutSam3Item : OfCutoutIsnetItem;
            OfCutoutHeldItemsBox.IsChecked = _database?.GetStoredCutoutHeldItems() ?? true;
            PushCutoutSettingsToService();
        }
        finally
        {
            _cutoutSettingsLoading = false;
        }
    }

    private SubjectCutoutModel SelectedCutoutModel =>
        OfCutoutModelBox.SelectedItem is ComboBoxItem { Tag: string id }
            ? SubjectCutoutModels.FromId(id)
            : SubjectCutoutModel.IsnetAnime;

    private void PushCutoutSettingsToService()
    {
        var model = SelectedCutoutModel;
        OfCutoutHeldItemsBox.IsEnabled = model == SubjectCutoutModel.Sam3;
        if (_autoOverFrameArtService is null)
            return;
        _autoOverFrameArtService.CutoutModel = model;
        _autoOverFrameArtService.IncludeHeldItems = OfCutoutHeldItemsBox.IsChecked == true;
    }

    private void OfCutoutModel_SelectionChanged(object sender, SelectionChangedEventArgs e)
    {
        if (!IsLoaded)
            return;
        PushCutoutSettingsToService();
        if (_cutoutSettingsLoading)
            return;
        _database?.SetStoredCutoutModel(SubjectCutoutModels.ToId(SelectedCutoutModel));
        DiscardAutoGeneratedOfReplacement();
        if (SelectedCutoutModel == SubjectCutoutModel.Sam3)
            Status(Loc.T("overframe.cutout_sam3_selected"));
    }

    /// <summary>
    /// A Preview / Auto-create result made with the previous cutout settings would otherwise be
    /// reused by the next Preview. Manually chosen replacement images are left alone.
    /// </summary>
    private void DiscardAutoGeneratedOfReplacement()
    {
        if (_ofAutoGeneratedTempPath is null
            || !string.Equals(_ofReplacementImagePath, _ofAutoGeneratedTempPath, StringComparison.OrdinalIgnoreCase))
            return;

        CleanupOfAutoGeneratedTemp();
        _ofReplacementImagePath = null;
        OfReplacementImage.Source = null;
        ApplyOfPreviewLayout(hasReplacement: false);
    }

    private void OfCutoutHeldItems_Changed(object sender, RoutedEventArgs e)
    {
        if (!IsLoaded)
            return;
        PushCutoutSettingsToService();
        if (_cutoutSettingsLoading)
            return;
        _database?.SetStoredCutoutHeldItems(OfCutoutHeldItemsBox.IsChecked == true);
        DiscardAutoGeneratedOfReplacement();
    }

    private void ApplyCutoutLocalizedUi()
    {
        OfCutoutLabel.Text = Loc.T("overframe.cutout_label");
        OfCutoutModelBox.ToolTip = Loc.T("overframe.cutout_tooltip");
        OfCutoutIsnetItem.Content = Loc.T("overframe.cutout_isnet");
        OfCutoutSam3Item.Content = Loc.T("overframe.cutout_sam3");
        OfCutoutHeldItemsBox.Content = Loc.T("overframe.cutout_held_items");
        OfCutoutHeldItemsBox.ToolTip = Loc.T("overframe.cutout_held_items_tooltip");
    }
}
